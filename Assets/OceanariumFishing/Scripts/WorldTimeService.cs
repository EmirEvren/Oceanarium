using UnityEngine;
namespace OceanariumFishing
{
    [DefaultExecutionOrder(-100)]
    public sealed class WorldTimeService:MonoBehaviour
    {
        public static WorldTimeService Current{get;private set;}public WorldSimulation Simulation{get;private set;}
        public bool IsAuthority=true;public WorldSettings Settings=>Simulation?.Settings;float saveAge;
        public static WorldTimeService Ensure(FishCollection data)
        {
            if(Current)return Current;var settings=Resources.Load<WorldSettings>("WorldSettings");if(!settings)return null;
            var go=new GameObject("World time authority");var service=go.AddComponent<WorldTimeService>();
            var state=data.world??new WorldState{minute=(long)(data.town.residents.Count>0?data.town.elapsedMinutes:settings.startHour*60)};
            service.Simulation=new(state,settings);go.AddComponent<WorldPresentation>();go.AddComponent<WorldCalendarHUD>();return service;
        }
        void Awake(){if(Current&&Current!=this){Destroy(gameObject);return;}Current=this;DontDestroyOnLoad(gameObject);}
        void Update(){if(Simulation==null||!IsAuthority||!GamePlayers.Inventory)return;Simulation.Tick(Time.deltaTime);saveAge+=Time.unscaledDeltaTime;if(saveAge>=15){Flush();saveAge=0;}}
        public void ApplyWorld(WorldState state,bool authority){IsAuthority=authority;if(Simulation!=null)Simulation.ApplySnapshot(state);else Simulation=new(state,Resources.Load<WorldSettings>("WorldSettings"));}
        public bool Flush(){var inventory=GamePlayers.Inventory;if(!IsAuthority||!inventory||Simulation==null)return false;return inventory.CommitAquarium(inventory.Collection.Copy());}
        public void Stamp(FishCollection data){if(Simulation==null)return;data.world=Simulation.State.Copy();data.town.elapsedMinutes=data.world.minute+data.world.fraction;}
        public bool AdvanceTo(long minute)
        {
            if(!IsAuthority||Simulation==null)return false;var inventory=GamePlayers.Inventory;if(!inventory)return false;
            var next=inventory.Collection.Copy();next.world=Simulation.State.Copy();next.world.minute=System.Math.Max(0,minute);next.world.fraction=0;next.town.elapsedMinutes=next.world.minute;
            // Save before publishing a jump; no daily income is generated by this path.
            if(!FishCollectionStore.Save(next))return false;Simulation.ApplySnapshot(next.world);inventory.CommitAquarium(next);return true;
        }
        void OnApplicationPause(bool paused){if(paused)Flush();}
        void OnApplicationQuit(){Flush();}
        void OnDestroy(){if(Current==this)Current=null;}
    }
}
